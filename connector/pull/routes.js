/** Yield every file under `dir`, recursively. */
function walk(dir, files = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return files;
  }

  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else files.push(full);
  }

  return files;
}

/**
 * Where a template file maps back to in the root, if anywhere.
 *
 * Uses the CENTRAL RESOLVER for dynamic routing, with the route table
 * as a fallback for special cases (generated files, bundle configs).
 *
 * @param {string} template - "react" | "expo"
 * @param {string} templateRel - path relative to template/<template>
 * @returns {{rootPath: string, prefer?: string|null, stylesheet?: boolean, bundle?: boolean}|null}
 *   null for files no route claims (template scaffolding, generated entries)
 */
function routeFor(template, templateRel) {
  const posix = templateRel.split(path.sep).join("/");

  // First, check if this is a generated file (should not be pulled)
  if (isGeneratedPath(posix, template)) {
    return null;
  }

  // Try the central resolver first for dynamic routing
  const resolvedSource = getSourcePathFromTarget(posix, template);
  if (resolvedSource) {
    // Check for special cases that need additional metadata
    if (posix === "global.css" || posix.endsWith("/global.css")) {
      return {
        rootPath: "src/global.css",
        stylesheet: true,
      };
    }
    
    // Check for bundle configs
    if (posix === "package.json" || posix === "tsconfig.json") {
      return {
        rootPath: posix,
        bundle: true,
      };
    }

    return {
      rootPath: resolvedSource,
    };
  }

  // Fall back to the route table for special cases
  for (const route of ROUTES[template] ?? []) {
    if (route.file) {
      if (posix !== route.file) continue;
      if (route.ignore) return null;
      return {
        rootPath: route.to ? route.to(posix) : posix,
        stylesheet: route.stylesheet,
        bundle: route.bundle,
        prefer: route.prefer ? route.prefer(posix) : null,
      };
    }

    if (posix !== route.dir && !posix.startsWith(`${route.dir}/`)) continue;

    const rel = posix === route.dir ? "" : posix.slice(route.dir.length + 1);
    const match = route.match ? route.match.exec(rel) : null;
    if (route.match && !match) continue;
    if (route.ignore) return null;

    return {
      rootPath: route.to(rel, match),
      prefer: route.prefer ? route.prefer(rel) : null,
      stylesheet: route.stylesheet,
      bundle: route.bundle,
    };
  }

  return null;
}

module.exports = { ROUTES, NOTES, walk, routeFor };
