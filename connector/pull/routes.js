// Add a catch-all for dynamic folders that don't match known directories
// This handles @foo, @bar, @services, @anything, and nested variants
function addDynamicRoutes() {
  // For expo: any file/dir at the root that's not in a known location
  // maps back with @ prefix: foo/bar.tsx -> src/@foo/bar.tsx
  const expoDynamic = {
    to: (rel) => {
      const segments = rel.split("/");
      if (segments.length > 0 && !segments[0].startsWith("@")) {
        segments[0] = "@" + segments[0];
        return `src/${segments.join("/")}`;
      }
      return `src/${rel}`;
    }
  };
  
  // Add as a catch-all entry (checked last)
  ROUTES.expo.push({
    // This matches anything that wasn't matched above
    to: expoDynamic.to,
  });
}

// Initialize dynamic routes
